// Normalize medicine name for matching across variants
fn normalize_medicine_name(name: &str) -> String {
    let lower = name.trim().to_lowercase();
    // Normalize known synonyms/variants
    if lower.contains("ekangavira") || lower.contains("ekangaveera") {
        return "ekangaveera rasa".to_string();
    }
    if lower.contains("yograj guggulu") || lower.contains("yogaraja guggulu") {
        return "yogaraja guggulu".to_string();
    }
    if lower.contains("mahayogaraja") || lower.contains("maha yogaraja") {
        return "maha yogaraja guggulu".to_string();
    }
    if lower.contains("maharasnadi kwatha") || lower.contains("maharasnadi kashayam") {
        return "maharasnadi kashayam".to_string();
    }
    if lower.contains("nishamalaki powder") || lower.contains("nishamalaki churna") {
        return "nishamalaki churna".to_string();
    }
    if lower.contains("sudarshana ghana vati") || lower.contains("mahasudarshan ghan vati") {
        return "mahasudarshan ghan vati".to_string();
    }
    lower
}

pub async fn seed_clinical_datasets_if_empty(pool: &DbPool) -> Result<(), Box<dyn std::error::Error>> {
    let ref_count: (i64,) = sqlx::query_as("SELECT COUNT(*) FROM clinical_references")
        .fetch_one(pool)
        .await?;

    if ref_count.0 == 0 {
        info!("Seeding BAMS-Validated and CCRAS Clinical Reference Datasets with deduplication...");

        let now_str = Utc::now().to_rfc3339();
        let mut tx = pool.begin().await?;

        // Combine both sets: BAMS (56) + CCRAS (83) = 139 references
        let all_records = BAMS_REFS.iter().chain(CCRAS_REFS.iter());

        for rec in all_records {
            let norm_key = normalize_medicine_name(rec.medicine_name);

            // 1. Check if matching medicine exists in master
            let existing_med: Option<(String,)> = sqlx::query_as(
                "SELECT id FROM medicines 
                 WHERE LOWER(name) = ? OR LOWER(name) = ? OR code = ?"
            )
            .bind(&norm_key)
            .bind(rec.medicine_name.trim().to_lowercase())
            .bind(format!("MED-{}", norm_key.replace(' ', "-").to_uppercase()))
            .fetch_optional(&mut *tx)
            .await?;

            let medicine_id = match existing_med {
                Some((id,)) => id,
                None => {
                    // Generate a stable code & new record
                    let clean_code = format!(
                        "MED-{}",
                        norm_key
                            .replace(|c: char| !c.is_alphanumeric(), "-")
                            .trim_matches('-')
                            .to_uppercase()
                    );
                    let med_id = format!("med_{}", Uuid::now_v7());

                    sqlx::query(
                        "INSERT INTO medicines (id, code, name, form, source, source_reference, validation_status, status, created_at, updated_at)
                         VALUES (?, ?, ?, ?, ?, ?, ?, 'ACTIVE', ?, ?)"
                    )
                    .bind(&med_id)
                    .bind(&clean_code)
                    .bind(rec.medicine_name)
                    .bind(rec.formulation_form)
                    .bind(rec.source)
                    .bind(rec.source_reference)
                    .bind(rec.validation_status)
                    .bind(&now_str)
                    .bind(&now_str)
                    .execute(&mut *tx)
                    .await?;

                    med_id
                }
            };

            // 2. Insert the source-verified clinical reference
            let ref_id = format!("cref_{}", Uuid::now_v7());
            sqlx::query(
                "INSERT INTO clinical_references (
                    id, medicine_id, chief_complaint, duration_context, roga_name,
                    namc_code, formulation_form, dose, frequency, anupana,
                    source, source_reference, source_page, validation_status,
                    dataset_version, imported_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)"
            )
            .bind(&ref_id)
            .bind(&medicine_id)
            .bind(rec.chief_complaint)
            .bind(rec.duration_context)
            .bind(rec.roga_name)
            .bind(rec.namc_code)
            .bind(rec.formulation_form)
            .bind(rec.dose)
            .bind(rec.frequency)
            .bind(rec.anupana)
            .bind(rec.source)
            .bind(rec.source_reference)
            .bind(rec.source_page)
            .bind(rec.validation_status)
            .bind(rec.dataset_version)
            .bind(&now_str)
            .execute(&mut *tx)
            .await?;
        }

        tx.commit().await?;
        info!("BAMS & CCRAS Clinical Datasets seeded successfully with strict provenance preservation.");
    }

    // Always ensure clinical_references are linked to diagnosis_catalog entries
    let _ = sqlx::query(
        "UPDATE clinical_references 
         SET diagnosis_id = (
             SELECT d.id FROM diagnosis_catalog d 
             WHERE UPPER(d.code) = UPPER(clinical_references.namc_code)
             LIMIT 1
         )
         WHERE namc_code IS NOT NULL AND diagnosis_id IS NULL"
    )
    .execute(pool)
    .await;

    let _ = sqlx::query(
        "UPDATE clinical_references 
         SET diagnosis_id = (
             SELECT d.id FROM diagnosis_catalog d 
             WHERE LOWER(d.name) = LOWER(clinical_references.roga_name)
                OR LOWER(d.name) LIKE '%' || LOWER(clinical_references.roga_name) || '%'
                OR LOWER(clinical_references.roga_name) LIKE '%' || LOWER(d.name) || '%'
             LIMIT 1
         )
         WHERE diagnosis_id IS NULL"
    )
    .execute(pool)
    .await;

    // Seed validated clinical rules for BAMS conditions
    seed_bams_rules_if_missing(pool).await?;

    Ok(())
}

pub async fn seed_bams_rules_if_missing(pool: &DbPool) -> Result<(), Box<dyn std::error::Error>> {
    let now_str = Utc::now().to_rfc3339();

    for rec in BAMS_REFS {
        let diag: Option<(String,)> = sqlx::query_as(
            "SELECT id FROM diagnosis_catalog WHERE UPPER(code) = UPPER(?)"
        )
        .bind(rec.namc_code)
        .fetch_optional(pool)
        .await?;

        let diag_id = match diag {
            Some((id,)) => id,
            None => continue,
        };

        let rule_code = format!("RULE-{}-V1", rec.namc_code);
        let rule_id = format!("rule_{}", rec.namc_code.to_lowercase().replace('-', "_"));

        let existing_rule: Option<(String,)> = sqlx::query_as(
            "SELECT id FROM clinical_rules WHERE diagnosis_id = ? AND version = 1"
        )
        .bind(&diag_id)
        .fetch_optional(pool)
        .await?;

        let active_rule_id = match existing_rule {
            Some((r_id,)) => r_id,
            None => {
                let pathya = "Light, freshly cooked diet, warm water, suitable seasonal regimen";
                let apathya = "Heavy, fried, excessively cold, stale or incompatible food, suppression of natural urges";
                let admin_exists: bool = sqlx::query_as::<_, (i64,)>("SELECT COUNT(*) FROM users WHERE id = 'usr_admin'")
                    .fetch_one(pool)
                    .await
                    .map(|r| r.0 > 0)
                    .unwrap_or(false);
                let val_by: Option<&str> = if admin_exists { Some("usr_admin") } else { None };

                sqlx::query(
                    "INSERT INTO clinical_rules (id, diagnosis_id, rule_code, version, criteria_json, anupana, pathya, apathya, status, validated_by, validated_at, created_at, updated_at)
                     VALUES (?, ?, ?, 1, '{}', ?, ?, ?, 'ACTIVE', ?, ?, ?, ?)"
                )
                .bind(&rule_id)
                .bind(&diag_id)
                .bind(&rule_code)
                .bind(rec.anupana)
                .bind(pathya)
                .bind(apathya)
                .bind(val_by)
                .bind(&now_str)
                .bind(&now_str)
                .bind(&now_str)
                .execute(pool)
                .await?;
                rule_id
            }
        };

        let norm_key = normalize_medicine_name(rec.medicine_name);
        let med: Option<(String,)> = sqlx::query_as(
            "SELECT id FROM medicines WHERE LOWER(name) = ? OR LOWER(name) = ? LIMIT 1"
        )
        .bind(&norm_key)
        .bind(rec.medicine_name.trim().to_lowercase())
        .fetch_optional(pool)
        .await?;

        if let Some((med_id,)) = med {
            let item_id = format!("cri_{}_{}", rec.namc_code.to_lowercase().replace('-', "_"), med_id.chars().take(8).collect::<String>());
            sqlx::query(
                "INSERT OR IGNORE INTO clinical_rule_items (id, rule_id, medicine_id, dosage_text, frequency_text, duration_text, instructions_text)
                 VALUES (?, ?, ?, ?, ?, ?, ?)"
            )
            .bind(&item_id)
            .bind(&active_rule_id)
            .bind(&med_id)
            .bind(rec.dose)
            .bind(rec.frequency)
            .bind(rec.duration_context)
            .bind(rec.anupana)
            .execute(pool)
            .await?;
        }
    }

    Ok(())
}
